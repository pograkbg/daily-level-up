  id smallserial primary key,
  grade smallint not null check (grade = 2),
  semester smallint not null check (semester in (1, 2)),
  category text not null,
  word text not null,
  meaning_ko text not null,
  unique (semester, word)
);

alter table public.grade2_words enable row level security;

drop policy if exists grade2_words_read on public.grade2_words;
create policy grade2_words_read on public.grade2_words
  for select to authenticated using (true);

